const fs = require('node:fs/promises');
const path = require('node:path');
const esbuild = require('esbuild');

const root = path.resolve(__dirname, '..');
async function buildDemo({ write = true } = {}) {
  const result = await esbuild.build({
    entryPoints: [path.join(__dirname, 'demo-runtime.js')],
    outfile: path.join(root, 'web/demo-runtime.js'),
    bundle: true, write, platform: 'browser', format: 'iife', target: ['es2020'],
    legalComments: 'none', charset: 'utf8',
    banner: { js: '// Generated by npm run build:demo from scripts/demo-runtime.js and gas/*.gs. Do not edit.' },
    plugins: [{
      name: 'real-gas-business-rules',
      setup(build) {
        build.onResolve({ filter: /^tapin:gas$/ }, () => ({ path: 'gas', namespace: 'tapin' }));
        build.onLoad({ filter: /.*/, namespace: 'tapin' }, async () => {
          const directory = path.join(root, 'gas');
          const files = (await fs.readdir(directory)).filter(file => file.endsWith('.gs')).sort();
          const sources = await Promise.all(files.map(async file => `// gas/${file}\n${await fs.readFile(path.join(directory, file), 'utf8')}`));
          return { loader: 'js', contents: `export function createGas(services) {\nconst { SpreadsheetApp, PropertiesService, LockService, Utilities, ContentService, DriveApp, Date } = services;\n${sources.join('\n')}\nreturn { doGet, doPost, setAdminCredential, getRuntimeConfig_, effectivePunches_, requireEmployeeByDevice_ };\n}` };
        });
      }
    }],
  });
  return write ? undefined : result.outputFiles[0].text;
}
if (require.main === module) buildDemo().catch(error => { console.error(error); process.exitCode = 1; });
module.exports = { buildDemo };
